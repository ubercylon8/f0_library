#!/bin/bash
# build_all.sh — a3d9b4c7 (T1083 Pre-Encryption File Enumeration)
#
# Builds the orchestrator; if tools/Seatbelt.exe is present it is embedded into
# the binary via the generated seatbelt_embed_real.go (build tag `seatbelt`),
# making the deployment truly single-binary (CLAUDE.md rule 3).
#
# Seatbelt provenance (option B — build from pinned source, 2026-11-03):
#   source: https://github.com/GhostPack/Seatbelt @ 392171df84472591d4eae7ebd5b1cdc96ba91377
#   built:  net472 (framework-dependent) via SDK-style shim + reference assemblies
#   sha256: ee09f12b1db66b578dfe2502359c5ddf9dcb07b74633b53e53926658c573800e
#
# The tool binary itself is NEVER committed (gitignored: tools/*.exe,
# seatbelt_embed_real.go). Place a self-built Seatbelt.exe in tools/ to embed.
set -e

cd "$(dirname "$0")"
ROOT="$(cd ../../.. && pwd)"

EMBED_FILE="seatbelt_embed_real.go"

if [[ -f tools/Seatbelt.exe ]]; then
    SHA=$(sha256sum tools/Seatbelt.exe | awk '{print $1}')
    echo "[INFO] Embedding tools/Seatbelt.exe (sha256: $SHA)"
    # Generate the tagged source file with the binary as a byte array
    python3 - "$SHA" <<'PYEOF'
import sys
sha = sys.argv[1]
data = open("tools/Seatbelt.exe", "rb").read()
with open("seatbelt_embed_real.go", "w") as f:
    f.write("//go:build windows && seatbelt\n// +build windows,seatbelt\n\n")
    f.write("// GENERATED by build_all.sh — do not edit or commit.\n")
    f.write(f"// tools/Seatbelt.exe sha256: {sha}\n\npackage main\n\n")
    f.write("var seatbeltEmbedded = []byte{")
    f.write(",".join(str(b) for b in data))
    f.write("}\n")
PYEOF
    TAGS="-tags seatbelt"
    echo "[INFO] Generated $EMBED_FILE"
else
    echo "[INFO] tools/Seatbelt.exe not present — building WITHOUT embedded Seatbelt"
    echo "[INFO] (test will runtime-load from c:\\F0\\tools\\Seatbelt.exe if present, else skip those phases)"
    rm -f "$EMBED_FILE"
    TAGS=""
fi

OUT_DIR="$ROOT/build/a3d9b4c7-2e8f-9d6a-3b0c-7f8a9b0c1d07"
mkdir -p "$OUT_DIR"

GOOS=windows GOARCH=amd64 CGO_ENABLED=0 go build $TAGS -o "$OUT_DIR/a3d9b4c7-2e8f-9d6a-3b0c-7f8a9b0c1d07.exe" .
echo "[SUCCESS] Built: $OUT_DIR/a3d9b4c7-2e8f-9d6a-3b0c-7f8a9b0c1d07.exe ($(du -h "$OUT_DIR/a3d9b4c7-2e8f-9d6a-3b0c-7f8a9b0c1d07.exe" | cut -f1))"

# Sign (fail-loud when signing is configured, per CLAUDE.md 2026-10-15)
#   - ProjectAchilles build service: F0_SIGN_CERT_PATH + F0_SIGN_CERT_PASS_FILE.
#     utils/codesign only knows signing-certs/ (gitignored, absent on PA servers),
#     so sign with osslsigncode directly, password via file (never on argv).
#   - Local f0_library checkout: signing-certs/F0RT1KA.pfx via utils/codesign.
BIN="$OUT_DIR/a3d9b4c7-2e8f-9d6a-3b0c-7f8a9b0c1d07.exe"
if [[ -n "${F0_SIGN_CERT_PATH:-}" ]]; then
    command -v osslsigncode >/dev/null || { echo "[ERROR] osslsigncode not installed but F0_SIGN_CERT_PATH is set — aborting (fail-loud)" >&2; exit 1; }
    [[ -f "${F0_SIGN_CERT_PASS_FILE:-}" ]] || { echo "[ERROR] F0_SIGN_CERT_PASS_FILE missing/unreadable (${F0_SIGN_CERT_PASS_FILE:-unset}) — aborting (fail-loud)" >&2; exit 1; }
    rm -f "$BIN.signed"
    osslsigncode sign -pkcs12 "$F0_SIGN_CERT_PATH" -readpass "$F0_SIGN_CERT_PASS_FILE" -in "$BIN" -out "$BIN.signed" \
        || { rm -f "$BIN.signed"; echo "[ERROR] osslsigncode failed (cert=$F0_SIGN_CERT_PATH) — aborting (fail-loud)" >&2; exit 1; }
    mv "$BIN.signed" "$BIN"
    echo "[SUCCESS] Signed (ProjectAchilles active cert)"
elif [[ -f "$ROOT/signing-certs/F0RT1KA.pfx" ]]; then
    "$ROOT/utils/codesign" sign "$BIN" || { echo "[ERROR] Signing failed — aborting (fail-loud)" >&2; exit 1; }
    echo "[SUCCESS] Signed"
else
    echo "[WARNING] No signing configuration — binary is UNSIGNED (dev-only)"
fi
sha1sum "$OUT_DIR/a3d9b4c7-2e8f-9d6a-3b0c-7f8a9b0c1d07.exe" | awk '{print "[INFO] SHA1: " $1}'
