// shellcode_windows.go — position-independent marker payloads for the
// T1055.003 stage (resolved-API form).
//
// Hand-written amd64 shellcode (GNU as --64 + objcopy; source kept with the
// test build notes). Each stub writes a marker file inside the decoy
// chrome.exe host, proving code execution under the browser-named process:
//
//   scRemoteThread  — clean RET variant; started via CreateRemoteThread,
//                     thread exits normally through RtlUserThreadStart.
//   scThreadHijack  — parks the hijacked thread in an endless loop after
//                     writing its marker; the injector terminates the host
//                     once the marker is observed.
//
// The `api` slot carries a magic placeholder (dec0ad0bbe0bfeed, little-endian
// in the byte stream). The INJECTOR patches it with kernel32!CreateFileA
// resolved in its own process before WriteProcessMemory — standard injector
// tradecraft: GetProcAddress follows Win11 KERNELBASE forwarders, and system
// DLLs share one ASLR base per boot session, so the address is valid inside
// the host process. No hardcoded addresses, no encoders, no packers — the
// bytes stay deterministic and auditable (EDR heuristics still observe the
// classic VirtualAllocEx/WriteProcessMemory/CreateRemoteThread chain, which
// is the detection surface under test).

